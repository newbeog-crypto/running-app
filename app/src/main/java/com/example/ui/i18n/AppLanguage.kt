enum class AppLanguage(val code: String, val nativeLabel: String) {
    KO("ko", "한국어"),
    EN("en", "English"),
    ZH("zh", "中文");

    companion object {
        fun fromCode(code: String?): AppLanguage {
            if (code != null) {
                entries.firstOrNull { it.code.equals(code, ignoreCase = true) }?.let { return it }
            }
            val sys = Locale.getDefault().language
            return when {
                sys.startsWith("ko") -> KO
                sys.startsWith("zh") -> ZH
                else -> EN
            }
        }
    }
}

